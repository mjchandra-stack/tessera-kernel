//! **The whole fuzz suite as one program**, so a build can depend on it.
//!
//! The generated per-schema tests already run these targets under
//! `bazel test`. That is not enough to say anything in a *certificate*: a test
//! result is not a build input, so an artifact can be produced while its fuzz
//! tests are failing, and a kernel compiled with "the fuzzing passed" baked in
//! would be stating something its own build never checked.
//!
//! This runner is what makes the claim true instead. It links every generated
//! target, runs them, and exits non-zero on the first finding. A genrule runs
//! it to produce the evidence record the kernel is compiled with — so the
//! kernel **cannot be built** unless this run was clean, and "the binary
//! exists" is the evidence rather than a note somebody wrote.
//!
//! What it does not cover: the hand-written blob parsers, which stay a test.
//! They need a seed built at runtime by the store's own builder, and linking
//! them here would make a kernel build depend on `api/image-store` for reasons
//! that have nothing to do with the kernel.

fn main() -> std::process::ExitCode {
    let mut targets = Vec::new();
    for set in [
        audio_output_fuzz::targets(),
        bench_result_fuzz::targets(),
        block_driver_fuzz::targets(),
        certification_fuzz::targets(),
        channel_msg_fuzz::targets(),
        clock_controller_fuzz::targets(),
        crypto_service_fuzz::targets(),
        demo_verdict_fuzz::targets(),
        device_abi_fuzz::targets(),
        display_output_fuzz::targets(),
        driver_bind_fuzz::targets(),
        driver_lifecycle_fuzz::targets(),
        firmware_fuzz::targets(),
        gpio_controller_fuzz::targets(),
        handle_abi_fuzz::targets(),
        image_store_fuzz::targets(),
        input_device_fuzz::targets(),
        kernel_event_fuzz::targets(),
        memory_abi_fuzz::targets(),
        network_driver_fuzz::targets(),
        port_event_fuzz::targets(),
        power_manager_fuzz::targets(),
        process_abi_fuzz::targets(),
        syscall_abi_fuzz::targets(),
        syscall_handle_ops_fuzz::targets(),
        usb_host_fuzz::targets(),
    ] {
        targets.extend(set);
    }

    let (coverage, finding) = tessera_isl_fuzz::run(&targets, ITERATIONS, SEED);
    if let Some(finding) = finding {
        eprintln!("fuzz: {finding:?}");
        eprintln!("fuzz: reproduce with that target, seed and iteration");
        return std::process::ExitCode::FAILURE;
    }
    if coverage.accepted == 0 || coverage.rejected == 0 {
        eprintln!("fuzz: one-sided run, nothing proved: {coverage:?}");
        return std::process::ExitCode::FAILURE;
    }

    // The evidence record, on stdout: what ran, over how much, from which
    // seed. Numbers rather than a boolean, because a certificate that said
    // only "fuzzed" would be as unfalsifiable as a log that does not say how
    // many records it read.
    println!("// SPDX-License-Identifier: Apache-2.0");
    println!("// Copyright 2026 Jagadeesh Chandra Muddana <mjchandra@gmail.com>");
    println!("// @generated by the fuzz runner — do not edit.");
    println!("#![no_std]");
    println!("/// Frozen structs fuzzed when this artifact was built.");
    println!("pub const TARGETS: u32 = {};", coverage.targets);
    println!("/// Inputs they were given.");
    println!("pub const INPUTS: u32 = {};", coverage.inputs);
    println!("/// Inputs the decoders accepted, so a one-sided run is visible.");
    println!("pub const ACCEPTED: u32 = {};", coverage.accepted);
    println!("/// The seed the run started from, so it repeats exactly.");
    println!("pub const SEED: u64 = {};", SEED);
    std::process::ExitCode::SUCCESS
}

/// Inputs per target. Matches what the generated per-schema tests use, so the
/// build-time run and the test-time run explore the same ground.
const ITERATIONS: u32 = 2000;
const SEED: u64 = 0x151_f022_9eed;
